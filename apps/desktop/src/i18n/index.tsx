const dicts = { zh, en };
export type Lang = keyof typeof dicts;
export type Dict = typeof zh;

export function useI18n(): { t: Dict; lang: Lang } {
  const lang = useSettings((s) => s.settings.uiLang);
  return { t: dicts[lang] as Dict, lang };
}
